"""Strict Pydantic schemas separating probabilistic Gemini outputs from deterministic execution."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, datetime
from enum import StrEnum
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator


class StrategyType(StrEnum):
    TRAILING_MOMENTUM = "TRAILING_MOMENTUM"
    SMART_MONEY = "SMART_MONEY"
    WHEEL = "WHEEL"
    CREDIT_SPREAD = "CREDIT_SPREAD"


class TradeAction(StrEnum):
    BUY_EQUITY = "BUY_EQUITY"
    ADD_DIP_TRANCHE = "ADD_DIP_TRANCHE"
    SELL_CSP = "SELL_CSP"
    BUY_TO_CLOSE_CSP = "BUY_TO_CLOSE_CSP"
    SELL_CC = "SELL_CC"
    BUY_TO_CLOSE_CC = "BUY_TO_CLOSE_CC"
    OPEN_BULL_PUT_SPREAD = "OPEN_BULL_PUT_SPREAD"
    CLOSE_BULL_PUT_SPREAD = "CLOSE_BULL_PUT_SPREAD"
    OPEN_IRON_CONDOR = "OPEN_IRON_CONDOR"
    CLOSE_IRON_CONDOR = "CLOSE_IRON_CONDOR"
    HOLD = "HOLD"
    REJECT = "REJECT"


class OptionRight(StrEnum):
    PUT = "PUT"
    CALL = "CALL"


class WheelState(StrEnum):
    IDLE = "IDLE"
    CSP_OPEN = "CSP_OPEN"
    ASSIGNED_SHARES = "ASSIGNED_SHARES"
    CC_OPEN = "CC_OPEN"
    CALLED_AWAY = "CALLED_AWAY"


class PolicyId(StrEnum):
    PASS = "PASS"
    TRD_POL_001 = "TRD-POL-001"  # Single-Ticker Concentration Cap
    TRD_POL_002 = "TRD-POL-002"  # Cash-Secured Put Collateral Lock
    TRD_POL_003 = "TRD-POL-003"  # Covered Call Cost-Basis Floor
    TRD_POL_004 = "TRD-POL-004"  # Bounded Dip-Laddering Cap
    TRD_POL_005 = "TRD-POL-005"  # Idempotency & Rate Cooldown
    TRD_POL_006 = "TRD-POL-006"  # Portfolio Intraday Circuit Breaker


class RiskDecisionStatus(StrEnum):
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    HALT_TRIGGERED = "HALT_TRIGGERED"


class MarketContextPacket(BaseModel):
    """
    Pre-aggregated, deterministic market context passed to Gemini (`analyst.py`).
    All external unstructured text must be sanitized before populating `catalyst_summary`.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    ticker: str = Field(..., min_length=1, max_length=12, pattern=r"^[A-Z.]+$")
    as_of_ny: datetime
    strategy_candidate: StrategyType
    price: float = Field(..., gt=0.0, description="Latest underlying price")
    atr_14d: float = Field(..., ge=0.0, description="14-day Average True Range")
    rsi_14d: float = Field(..., ge=0.0, le=100.0, description="14-day Relative Strength Index")
    realized_vol_20d: float = Field(default=0.20, ge=0.0, description="20-day annualized realized volatility")
    iv_rank: Optional[float] = Field(default=None, ge=0.0, le=100.0, description="Implied Volatility Rank [0-100]")
    spread_width_pct: float = Field(..., ge=0.0, description="Bid-ask spread width as fraction of mid")
    avg_daily_dollar_volume: float = Field(default=10_000_000.0, ge=0.0)
    return_20d: Optional[float] = Field(default=None, description="20-trading-day simple return")
    disclosure_filing_date: Optional[date] = None
    disclosure_lag_days: Optional[int] = Field(default=None, ge=0)
    catalyst_summary: str = Field(..., max_length=4000)


class TradeProposal(BaseModel):
    """
    Strict structured output contract emitted by Gemini.
    Invariant #3: Contains ZERO share quantities, option strikes, stop prices, or broker parameters.
    Any unexpected fields trigger a Pydantic ValidationError via `extra='forbid'`.
    """

    model_config = ConfigDict(extra="forbid")

    ticker: str = Field(..., min_length=1, max_length=12, pattern=r"^[A-Z.]+$")
    strategy: StrategyType
    action: TradeAction
    conviction_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Normalized analytical conviction score in [0.0, 1.0].",
    )
    rationale: str = Field(
        ...,
        min_length=5,
        max_length=1500,
        description="Structured quantitative and catalyst rationale.",
    )
    risk_flags: list[str] = Field(
        default_factory=list,
        description="Risk flags detected in context (e.g. 'HIGH_SPREAD', 'PROMPT_INJECTION_ATTEMPT').",
    )
    reject_reason: Optional[str] = Field(
        default=None,
        max_length=500,
        description="Explanation if action is HOLD or REJECT.",
    )

    @field_validator("ticker")
    @classmethod
    def _uppercase_ticker(cls, v: str) -> str:
        return v.strip().upper()


class OptionLegSpec(BaseModel):
    """Deterministic single leg within a defined-risk multi-leg (`MLEG`) options order."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    option_symbol: str = Field(..., min_length=6, max_length=32)
    right: OptionRight
    strike_price: float = Field(..., gt=0.0)
    expiration_date: date
    side: Literal["BUY", "SELL"]
    position_intent: Literal["buy_to_open", "sell_to_open", "buy_to_close", "sell_to_close"]
    ratio_qty: int = Field(default=1, ge=1, le=10)


class OrderIntent(BaseModel):
    """
    Deterministic order intent generated by Python strategy engines and gated by `RiskGateway`.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    strategy: StrategyType
    ticker: str = Field(..., min_length=1, max_length=12, pattern=r"^[A-Z.]+$")
    action: TradeAction
    qty: int = Field(..., gt=0, description="Number of shares, option contracts, or spread units")
    notional_exposure_delta: float = Field(
        ...,
        ge=0.0,
        description="Incremental underlying notional exposure / max spread loss added by this order ($)",
    )
    limit_price: Optional[float] = Field(
        default=None,
        gt=0.0,
        description="Positive limit price (for MLEG, net credit per spread on OPEN or net debit on CLOSE).",
    )
    trailing_stop_pct: Optional[float] = Field(default=None, gt=0.0, le=0.25)

    # Single-leg option fields (Wheel strategy)
    option_symbol: Optional[str] = None
    option_right: Optional[OptionRight] = None
    strike_price: Optional[float] = Field(default=None, gt=0.0)
    expiration_date: Optional[date] = None
    option_spread_pct: Optional[float] = Field(default=None, ge=0.0)

    # Multi-leg defined-risk option fields (MLEG Bull Put Spread / Iron Condor)
    legs: tuple[OptionLegSpec, ...] = Field(default_factory=tuple, max_length=4)
    spread_id: Optional[str] = None

    # Bounded dip-laddering metadata (TRD-POL-004)
    dip_tranche_index: int = Field(
        default=0,
        ge=0,
        description="0 for initial entry; 1..N for add-on dip tranches",
    )
    realized_vol_20d: float = Field(default=0.0, ge=0.0)

    # Idempotency & Auditability (TRD-POL-005)
    date_bucket: str = Field(..., min_length=8, description="America/New_York time bucket")
    proposal: Optional[TradeProposal] = None


class PortfolioSnapshot(BaseModel):
    """Deterministic account and position state queried prior to RiskGateway evaluation."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    as_of_ny: datetime
    total_equity: float = Field(..., ge=0.0)
    non_marginable_buying_power: float = Field(..., ge=0.0)
    daily_starting_equity: float = Field(..., gt=0.0)
    intraday_peak_equity: float = Field(..., gt=0.0)
    options_buying_power: Optional[float] = Field(default=None, ge=0.0)
    broker_reserved_csp_collateral: float = Field(
        default=0.0,
        ge=0.0,
        description="Cash collateral already deducted from broker buying power for existing short puts/open CSP orders.",
    )
    # Maps underlying ticker -> total notional exposure:
    #   equity market value + 100*strike*|qty| for short puts + long option value + pending open-order exposure
    ticker_notional_exposure: dict[str, float] = Field(default_factory=dict)

    def with_added_exposure(self, ticker: str, amount: float) -> "PortfolioSnapshot":
        """Return a copy with `amount` added to `ticker` exposure (intra-cycle bookkeeping)."""
        updated = dict(self.ticker_notional_exposure)
        updated[ticker] = updated.get(ticker, 0.0) + max(0.0, amount)
        return self.model_copy(update={"ticker_notional_exposure": updated})


class RiskDecision(BaseModel):
    """Structured outcome returned by `RiskGateway.evaluate_and_record()`."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    status: RiskDecisionStatus
    policy_id: PolicyId
    client_order_id: str
    reason: str
    audit_log_id: int


@dataclass(frozen=True)
class OptionContractQuote:
    """Deterministic snapshot of a single option contract quote and optional Greeks."""

    option_symbol: str
    underlying_ticker: str
    right: OptionRight
    strike_price: float
    expiration_date: date
    bid: float
    ask: float
    delta: Optional[float] = None
    theta: Optional[float] = None
    implied_volatility: Optional[float] = None

    @property
    def mid(self) -> float:
        return round(0.5 * (self.bid + self.ask), 4)

    @property
    def spread_pct(self) -> float:
        if self.bid <= 0.0 or self.ask <= 0.0 or self.ask < self.bid:
            return 1.0
        mid = 0.5 * (self.bid + self.ask)
        if mid <= 0.0:
            return 1.0
        return float((self.ask - self.bid) / mid)
